/**
 * 内置 200 套优化校准预设。
 *
 * ── 数据来源 ──
 * 前 166 套来自 nikonpc.com 的公开 NCP 库（社区沉淀二十年的真实配方，含
 * Fuji/Kodak/Agfa/Ferrania/Konica 胶片模拟、BeatLog/Flaat 电影 Log、SHING
 * 系列日系调、Tri-X/T-Max 黑白等）。抓取方式：POST `?cmd=loadNpc` 拿回
 * `splain.points` 里的原始 (x,y) 锚点，再用与本项目 [CubicSplineLut] 相同的
 * Fritsch–Carlson 单调样条插值成 256 点 LUT —— 曲线是真数据，不是编的。

 * 锐化 -3..9、清晰度 -5..5、对比 -3..3、亮度 -2..2、饱和度 -3..3、色相 -3..3。
 * pcdType：0 = 彩色族、1 = 单色、2 = 棕褐族、8 = 梦幻/玩具族。
 *
 * ── 相机名称 ──
 * 614 字节载荷名称区是 20 字节 ASCII，中文会变成下划线。所以每个配方都有
 * [BuiltInPreset.cameraName]（≤19 位 ASCII，真正写进机身的名字）与
 * [BuiltInPreset.displayName]（界面显示名）。
 */
data class BuiltInPreset(
    val id: String,
    /** 界面显示名 */
    val displayName: String,
    /** 写入机身的 ASCII 名（≤19） */
    val cameraName: String,
    val categoryId: String,
    val categoryLabel: String,
    /** 一句话说明，由曲线实际形状算出来（黑位/中灰/高光偏移 + 参数） */
    val note: String,
    /** 热门度，数字越小越靠前 */
    val rank: Int,
    val recipe: Recipe,
    /** 数据来源：ncp = nikonpc.com 真实配方，derived = 真实曲线派生 */
    val source: String = "ncp",
)


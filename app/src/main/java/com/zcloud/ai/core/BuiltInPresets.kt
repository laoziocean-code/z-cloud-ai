    /** 全部 200 套，按热门度排好序。 */
    val ALL: List<BuiltInPreset> = ALL_LIST.sortedBy { it.rank }

    /** 按分类取（保持热门度顺序）。 */
    fun byCategory(categoryId: String?): List<BuiltInPreset> =
        if (categoryId == null) ALL else ALL.filter { it.categoryId == categoryId }

    /** 按 id 取。 */
    fun byId(id: String): BuiltInPreset? = ALL_LIST.firstOrNull { it.id == id }

    /** 名称/说明/分类模糊搜索。 */
    fun search(query: String): List<BuiltInPreset> {
        val q = query.trim().lowercase()
        if (q.isEmpty()) return ALL
        return ALL.filter {
            it.displayName.lowercase().contains(q) ||
                it.cameraName.lowercase().contains(q) ||
                it.categoryLabel.contains(q) ||
                it.note.lowercase().contains(q)
        }
    }
